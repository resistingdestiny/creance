/**
 * Put the generated block into the document, keeping everything outside the
 * markers. Returns the file content to write.
 */
export function mergeDocument(existing: string | null, block: string): string {
  const body = `${BEGIN_MARKER}\n\n${block}\n\n${END_MARKER}`;
  if (existing) {
    const begin = existing.indexOf(BEGIN_MARKER);
    const end = existing.indexOf(END_MARKER);
    if (begin !== -1 && end !== -1 && end > begin) {
      return `${existing.slice(0, begin)}${body}${existing.slice(end + END_MARKER.length)}`;
    }
  }
  return `# Hedera testnet resources

Every id below was created by \`pnpm hedera:setup\` against Hedera testnet. The
script is idempotent: it reads \`docs/hedera.testnet.json\`, verifies each id on
the mirror node and creates only what is missing, so running it again prints
"nothing to do" and leaves this file untouched.

The block between the two markers is generated. Add new sections outside it.

${body}
${TEMPLATE_TAIL}`;
}
